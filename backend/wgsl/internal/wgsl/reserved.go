package wgsl

import "strings"

// SanitizeIdent replaces every character that is not legal in a WGSL
// identifier (letters, digits, underscore) with an underscore. Used to turn a
// package path such as "foo/bar" into a valid name prefix; a single-segment
// path like "omega" passes through unchanged.
func SanitizeIdent(name string) string {
	return strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_':
			return r
		default:
			return '_'
		}
	}, name)
}

func SanitizeVarName(varName string) string {
	if wgslReservedWords[varName] {
		return "gsl_var_" + varName
	}
	return varName
}

func SanitizeFnName(fnName string) string {
	if wgslReservedWords[fnName] {
		return "gsl_fn_" + fnName
	}
	return fnName
}

