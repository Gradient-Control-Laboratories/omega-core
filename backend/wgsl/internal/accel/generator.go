// GenerateOps generates the Go source code for ops_gen.go from a slice of
// validated PackageDescriptor sidecars.
func GenerateOps(descriptors []*PackageDescriptor) ([]byte, error) {
	// Sort descriptors by package name for deterministic generation
	sortedDescs := make([]*PackageDescriptor, len(descriptors))
	copy(sortedDescs, descriptors)
	sort.Slice(sortedDescs, func(i, j int) bool {
		return sortedDescs[i].Package < sortedDescs[j].Package
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tool/build-wgsl-accel-ops. DO NOT EDIT.\n\n")
	buf.WriteString("package accel\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"gradientcontrol.com/omega/core/backend/wgsl/internal/wgsl\"\n")
	buf.WriteString("\t\"gradientcontrol.com/omega/core/internal/build\"\n")
	buf.WriteString("\t\"gradientcontrol.com/omega/core/program\"\n")
	buf.WriteString(")\n\n")

	buf.WriteString("// OpKind indicates whether a WGSL hardware acceleration is an operator or a builtin.\n")
	buf.WriteString("type OpKind int\n\n")
	buf.WriteString("const (\n")
	buf.WriteString("\tOpKindOperator OpKind = iota\n")
	buf.WriteString("\tOpKindBuiltin\n")
	buf.WriteString(")\n\n")

	buf.WriteString("// OpTemplate defines the hardware acceleration mapping for a standard library operation.\n")
	buf.WriteString("type OpTemplate struct {\n")
	buf.WriteString("\tKind        OpKind\n")
	buf.WriteString("\tSymbol      string\n")
	buf.WriteString("\tBuiltin     string\n")
	buf.WriteString("\tPrecedence  build.Precedence\n")
	buf.WriteString("\tUnary       bool\n")
	buf.WriteString("\tTypeDeriver func(argTypes []wgsl.TypeInfo) (*program.Type, bool)\n")
	buf.WriteString("}\n\n")

	buf.WriteString("var libraryOps = map[string]OpTemplate{\n")

	for _, desc := range sortedDescs {
		// Sort accelerations by name for deterministic order
		sortedAccels := make([]Acceleration, len(desc.Accelerations))
		copy(sortedAccels, desc.Accelerations)
		sort.Slice(sortedAccels, func(i, j int) bool {
			return sortedAccels[i].Name < sortedAccels[j].Name
		})

		for _, accel := range sortedAccels {
			canonicalKey := desc.Package + "." + accel.Name
			buf.WriteString(fmt.Sprintf("\t%q: {\n", canonicalKey))

			switch accel.Kind {
			case "operator":
				buf.WriteString("\t\tKind: OpKindOperator,\n")
				buf.WriteString(fmt.Sprintf("\t\tSymbol: %q,\n", accel.Symbol))
			case "builtin":
				buf.WriteString("\t\tKind: OpKindBuiltin,\n")
				buf.WriteString(fmt.Sprintf("\t\tBuiltin: %q,\n", accel.Builtin))
			default:
				return nil, fmt.Errorf("package %q, accel %q: unknown kind %q", desc.Package, accel.Name, accel.Kind)
			}

			if accel.Precedence != "" {
				buf.WriteString(fmt.Sprintf("\t\tPrecedence: build.Precedence%s,\n", accel.Precedence))
			}
			if accel.Unary {
				buf.WriteString("\t\tUnary: true,\n")
			}

			deriverCode, err := generateTypeDeriver(accel)
			if err != nil {
				return nil, fmt.Errorf("package %q, accel %q: %w", desc.Package, accel.Name, err)
			}
			buf.WriteString("\t\tTypeDeriver: ")
			buf.WriteString(deriverCode)
			buf.WriteString(",\n")
			buf.WriteString("\t},\n")
		}
	}

	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format generated code: %w\nSource:\n%s", err, buf.String())
	}

	return formatted, nil
}

// GenerateInlinerRegistration generates the Go source code for common/program/inline/wgsl.go
// from a slice of validated PackageDescriptor sidecars, registering hardware-accelerated
// packages into hardwareAccelPkgs.
func GenerateInlinerRegistration(descriptors []*PackageDescriptor) ([]byte, error) {
	pkgSet := make(map[string]bool)
	for _, desc := range descriptors {
		if desc != nil && desc.Package != "" && len(desc.Accelerations) > 0 {
			pkgSet[desc.Package] = true
		}
	}

	pkgs := make([]string, 0, len(pkgSet))
	for p := range pkgSet {
		pkgs = append(pkgs, p)
	}
	sort.Strings(pkgs)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by tool/build-wgsl-accel-ops. DO NOT EDIT.\n\n")
	buf.WriteString("package inline\n\n")
	buf.WriteString("func init() {\n")
	for _, pkg := range pkgs {
		buf.WriteString(fmt.Sprintf("\thardwareAccelPkgs[%q] = true\n", pkg))
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format generated inliner registration: %w\nSource:\n%s", err, buf.String())
	}
	return formatted, nil
}

func generateTypeDeriver(accel Acceleration) (string, error) {
	var body strings.Builder
	body.WriteString("func(argTypes []wgsl.TypeInfo) (*program.Type, bool) {\n")

	for _, sig := range accel.Signatures {
		cond, ret, err := matchSignatureRule(accel, sig)
		if err != nil {
			return "", err
		}
		body.WriteString(fmt.Sprintf("\t\tif %s {\n", cond))
		body.WriteString(fmt.Sprintf("\t\t\treturn %s, true\n", ret))
		body.WriteString("\t\t}\n")
	}

	body.WriteString("\t\treturn nil, false\n")
	body.WriteString("\t}")
	return body.String(), nil
}

func matchSignatureRule(accel Acceleration, sig Signature) (cond string, ret string, err error) {
	args := sig.Args
	switch len(args) {
	case 1:
		arg0 := args[0]
		switch {
		case arg0 == "mat" && sig.Return == "mat":
			cond = "len(argTypes) == 1 && argTypes[0].IsNativeMatrix()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case arg0 == "vec" && sig.Return == "vec":
			cond = "len(argTypes) == 1 && argTypes[0].IsVector()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case strings.HasPrefix(arg0, "mat") && strings.HasSuffix(arg0, "x") || isMatNxN(arg0):
			dim := parseMatDim(arg0)
			if dim < 2 || dim > 4 {
				return "", "", fmt.Errorf("unsupported matrix dimension %q (must be 2..4)", arg0)
			}
			cond = fmt.Sprintf("len(argTypes) == 1 && argTypes[0].IsNativeMatrix() && func() bool { cols, rows, ok := argTypes[0].MatrixDimensions(); return ok && cols == %d && rows == %d }()", dim, dim)
			if sig.Return == "f32" {
				ret = "program.NewScalarType()"
			} else if isMatNxN(sig.Return) {
				ret = fmt.Sprintf("program.NewMatrixType(%d, program.NewListType(%d, program.NewScalarType()))", dim, dim)
			} else {
				return "", "", fmt.Errorf("unsupported return type %q for 1-arg signature %q", sig.Return, arg0)
			}
			return cond, ret, nil
		}

	case 2:
		arg0, arg1 := args[0], args[1]
		switch {
		case arg0 == "mat" && arg1 == "mat" && sig.Return == "mat":
			if accel.Symbol == "*" {
				cond = "len(argTypes) == 2 && argTypes[0].IsNativeMatrix() && argTypes[1].IsNativeMatrix() && func() bool { cols0, _, ok0 := argTypes[0].MatrixDimensions(); _, rows1, ok1 := argTypes[1].MatrixDimensions(); return ok0 && ok1 && cols0 == rows1 }()"
				ret = "program.NewMatrixType(func() int32 { cols1, _, _ := argTypes[1].MatrixDimensions(); return int32(cols1) }(), program.NewListType(func() int32 { _, rows0, _ := argTypes[0].MatrixDimensions(); return int32(rows0) }(), program.NewScalarType()))"
				return cond, ret, nil
			}
			// plus or minus (elementwise)
			cond = "len(argTypes) == 2 && argTypes[0].IsNativeMatrix() && argTypes[1].IsNativeMatrix() && func() bool { cols0, rows0, ok0 := argTypes[0].MatrixDimensions(); cols1, rows1, ok1 := argTypes[1].MatrixDimensions(); return ok0 && ok1 && cols0 == cols1 && rows0 == rows1 }()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case arg0 == "mat" && arg1 == "scalar" && sig.Return == "mat":
			cond = "len(argTypes) == 2 && argTypes[0].IsNativeMatrix() && argTypes[1].IsNumericScalar()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case arg0 == "scalar" && arg1 == "mat" && sig.Return == "mat":
			cond = "len(argTypes) == 2 && argTypes[0].IsNumericScalar() && argTypes[1].IsNativeMatrix()"
			ret = "argTypes[1].ProgType"
			return cond, ret, nil

		case arg0 == "mat" && arg1 == "vec" && sig.Return == "vec":
			cond = "len(argTypes) == 2 && ((argTypes[0].IsNativeMatrix() && argTypes[1].IsVector() && func() bool { cols, _, ok := argTypes[0].MatrixDimensions(); return ok && argTypes[1].VectorSize() == cols }()) || (argTypes[0].IsVector() && argTypes[1].IsNativeMatrix() && func() bool { _, rows, ok := argTypes[1].MatrixDimensions(); return ok && argTypes[0].VectorSize() == rows }()))"
			ret = "func() *program.Type { if argTypes[0].IsNativeMatrix() { _, rows, _ := argTypes[0].MatrixDimensions(); return program.NewListType(int32(rows), program.NewScalarType()) }; cols, _, _ := argTypes[1].MatrixDimensions(); return program.NewListType(int32(cols), program.NewScalarType()) }()"
			return cond, ret, nil

		case arg0 == "vec" && arg1 == "vec" && sig.Return == "vec":
			cond = "len(argTypes) == 2 && argTypes[0].IsVector() && argTypes[1].IsVector() && argTypes[0].VectorSize() == argTypes[1].VectorSize()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case arg0 == "vec" && arg1 == "scalar" && sig.Return == "vec":
			cond = "len(argTypes) == 2 && argTypes[0].IsVector() && argTypes[1].IsNumericScalar()"
			ret = "argTypes[0].ProgType"
			return cond, ret, nil

		case arg0 == "scalar" && arg1 == "vec" && sig.Return == "vec":
			cond = "len(argTypes) == 2 && argTypes[0].IsNumericScalar() && argTypes[1].IsVector()"
			ret = "argTypes[1].ProgType"
			return cond, ret, nil
		}
	}

	return "", "", fmt.Errorf("unsupported signature args=%v, return=%q", sig.Args, sig.Return)
}

func isMatNxN(s string) bool {
	if len(s) == 6 && strings.HasPrefix(s, "mat") && s[4] == 'x' && s[3] == s[5] {
		d := s[3]
		return d >= '2' && d <= '4'
	}
	return false
}

func parseMatDim(s string) int {
	if isMatNxN(s) {
		dim, _ := strconv.Atoi(string(s[3]))
		return dim
	}
	return 0
}
