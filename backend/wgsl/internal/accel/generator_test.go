package accel_test

import (
	"go/parser"
	"go/token"
	"path/filepath"
	"strings"
	"testing"

	"gradientcontrol.com/omega/core/backend/wgsl/internal/accel"
)

func TestGenerateOps_Valid(t *testing.T) {
	pkgRoot := filepath.Join("../../../..", "stdlib")
	descriptors, err := accel.ValidateAll(pkgRoot, "wgsl")
	if err != nil {
		t.Fatalf("ValidateAll(%s, \"wgsl\") failed: %v", pkgRoot, err)
	}

	code, err := accel.GenerateOps(descriptors)
	if err != nil {
		t.Fatalf("GenerateOps failed: %v", err)
	}

	// Verify that the emitted code is valid Go syntax
	fset := token.NewFileSet()
	_, err = parser.ParseFile(fset, "ops_gen.go", code, parser.AllErrors)
	if err != nil {
		t.Fatalf("generated code failed Go syntax check: %v\nCode:\n%s", err, string(code))
	}

	codeStr := string(code)
	expectedSubstrings := []string{
		"// Code generated by tool/build-wgsl-accel-ops. DO NOT EDIT.",
		"package accel",
		"type OpKind int",
		"OpKindOperator OpKind = iota",
		"OpKindBuiltin",
		"type OpTemplate struct",
		"var libraryOps = map[string]OpTemplate{",
		`"matrix.multiply":`,
		`"matrix.scale":`,
		`"matrix.plus":`,
		`"matrix.minus":`,
		`"matrix.negate":`,
		`"matrix.transpose2":`,
		`"matrix.transpose3":`,
		`"matrix.transpose4":`,
		`"matrix.determinant2":`,
		`"matrix.determinant3":`,
		`"matrix.determinant4":`,
		`"vector.multiply":`,
		`"vector.multiplyScalar":`,
		`"vector.multiplyComponents":`,
		`"vector.addVector":`,
		`"vector.addScalar":`,
		`"vector.subtractVector":`,
		`"vector.subtractScalarFrom":`,
		`"vector.subtractFromScalar":`,
		`"vector.divideByScalar":`,
		`"vector.divideScalarBy":`,
		`"vector.divideComponents":`,
		`"vector.negate":`,
	}

	for _, sub := range expectedSubstrings {
		if !strings.Contains(codeStr, sub) {
			t.Errorf("generated code missing expected substring %q", sub)
		}
	}
}

func TestGenerateOps_UnsupportedSignature(t *testing.T) {
	invalidDescriptors := []*accel.PackageDescriptor{
		{
			Package: "badpkg",
			Accelerations: []accel.Acceleration{
				{
					Name:   "badOp",
					Kind:   "operator",
					Symbol: "+",
					Signatures: []accel.Signature{
						{
							Args:   []string{"vec", "unknown_type"},
							Return: "vec",
						},
					},
				},
			},
		},
	}

	_, err := accel.GenerateOps(invalidDescriptors)
	if err == nil {
		t.Fatalf("expected error for unsupported signature [vec, unknown_type], got nil")
	}
}

